"""
Incident Report Generator Module
Formats and exports complete SOC incident reports in Markdown, JSON, and plaintext formats.
"""

from datetime import datetime
import json
from typing import Any, Dict
from modules.url_validator import defang_url


def generate_markdown_report(
    url: str,
    ml_result: Dict[str, Any],
    risk_result: Dict[str, Any],
    ai_report_text: str,
    vt_result: Dict[str, Any],
    urlhaus_result: Dict[str, Any],
    domain_intel: Dict[str, Any],
    incident_id: str = "N/A"
) -> str:
    """
    Assembles a full Markdown incident report.
    """
    safe_url = defang_url(url)
    timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

    md = f"""# 🛡️ SOAR Lite - Security Incident Triage Report
**Incident Reference:** `{incident_id}`  
**Generated At:** `{timestamp}`  
**Target URL (Defanged):** `{safe_url}`  

---

## 📊 Executive Threat Assessment
- **Classification Verdict:** `{ml_result.get('prediction', 'Unknown')}`
- **Model Confidence:** `{ml_result.get('confidence', 0.0) * 100:.1f}%`
- **Composite Risk Score:** `{risk_result.get('risk_score', 0)}/100` (`{risk_result.get('risk_category', 'Unknown')}`)
- **VirusTotal Telemetry:** `{vt_result.get('malicious_count', 0)} / {vt_result.get('total_engines', 0)} engines flagged`
- **URLhaus Telemetry:** `Listed: {urlhaus_result.get('is_listed', False)} (Threat: {urlhaus_result.get('threat', 'None')})`
- **Domain Metadata:** `Registrar: {domain_intel.get('registrar', 'Unknown')}, Age: {domain_intel.get('age_days', 0)} days`

---

## 🤖 AI Security Analyst Report
{ai_report_text}

---

## 🔍 Lexical & Structural URL Feature Telemetry
| Feature | Value |
| :--- | :--- |
| **URL Length** | `{ml_result.get('features', {}).get('url_length', 'N/A')}` |
| **Domain Length** | `{ml_result.get('features', {}).get('domain_length', 'N/A')}` |
| **Subdomain Count** | `{ml_result.get('features', {}).get('num_subdomains', 'N/A')}` |
| **HTTPS Enabled** | `{'Yes' if ml_result.get('features', {}).get('has_https') == 1 else 'No'}` |
| **Direct IP Host** | `{'Yes' if ml_result.get('features', {}).get('is_ip_address') == 1 else 'No'}` |
| **Brand Impersonation** | `{'Detected' if ml_result.get('features', {}).get('brand_impersonation') == 1 else 'None'}` |
| **Suspicious TLD** | `{'High Risk TLD' if ml_result.get('features', {}).get('suspicious_tld') == 1 else 'Standard'}` |
| **Shortener Service** | `{'Yes' if ml_result.get('features', {}).get('is_shortened') == 1 else 'No'}` |
| **Domain Shannon Entropy** | `{ml_result.get('features', {}).get('domain_entropy', 'N/A')}` |

---
*Report automatically generated by AI Phishing & Malicious URL Triage Dashboard (SOAR Lite).*
"""
    return md


def generate_json_report(
    url: str,
    ml_result: Dict[str, Any],
    risk_result: Dict[str, Any],
    ai_report_text: str,
    vt_result: Dict[str, Any],
    urlhaus_result: Dict[str, Any],
    domain_intel: Dict[str, Any],
    incident_id: str = "N/A"
) -> str:
    """
    Assembles a complete structured JSON incident report.
    """
    payload = {
        "report_metadata": {
            "platform": "AI Phishing & Malicious URL Triage Dashboard (SOAR Lite)",
            "incident_id": incident_id,
            "generated_timestamp": datetime.utcnow().isoformat() + "Z",
        },
        "target": {
            "url": url,
            "defanged_url": defang_url(url),
        },
        "classification": {
            "prediction": ml_result.get("prediction"),
            "confidence": ml_result.get("confidence"),
            "probabilities": ml_result.get("probabilities"),
        },
        "risk_scoring": {
            "risk_score": risk_result.get("risk_score"),
            "risk_category": risk_result.get("risk_category"),
            "components": risk_result.get("components"),
            "weights": risk_result.get("weights"),
        },
        "threat_intelligence": {
            "virustotal": vt_result,
            "urlhaus": urlhaus_result,
            "domain_intelligence": domain_intel,
        },
        "ai_analyst_report": ai_report_text,
        "features": ml_result.get("features", {}),
    }
    return json.dumps(payload, indent=2)
